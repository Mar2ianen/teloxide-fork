use std::ops::Range;

use serde::{Deserialize, Serialize};

use crate::types::{CustomEmojiId, User, UserId};

/// This object represents one special entity in a text message.
///
/// For example, hashtags, usernames, URLs, etc.
///
/// [The official docs](https://core.telegram.org/bots/api#messageentity).
#[serde_with::skip_serializing_none]
#[derive(Clone, Debug, Eq, Hash, PartialEq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
pub struct MessageEntity {
    #[serde(flatten)]
    pub kind: MessageEntityKind,

    /// Offset in UTF-16 code units to the start of the entity.
    pub offset: usize,

    /// Length of the entity in UTF-16 code units.
    pub length: usize,
}

/// A "parsed" [`MessageEntity`].
///
/// [`MessageEntity`] has offsets in UTF-**16** code units, but in Rust we
/// mostly work with UTF-**8**. In order to use an entity we need to convert
/// UTF-16 offsets to UTF-8 ones. This type represents a message entity with
/// converted offsets and a reference to the text.
///
/// You can get [`MessageEntityRef`]s by calling [`parse_entities`] and
/// [`parse_caption_entities`] methods of [`Message`] or by calling
/// [`MessageEntityRef::parse`].
///
/// [`parse_entities`]: crate::types::Message::parse_entities
/// [`parse_caption_entities`]: crate::types::Message::parse_caption_entities
/// [`Message`]: crate::types::Message
#[derive(Clone, Debug, Eq, Hash, PartialEq)]
pub struct MessageEntityRef<'a> {
    message: &'a str,
    range: Range<usize>,
    kind: &'a MessageEntityKind,
}

/// Checked map from Telegram UTF-16 code-unit offsets to UTF-8 byte offsets.
///
/// The map contains only Unicode scalar-value boundaries. In particular, an
/// offset in the middle of a UTF-16 surrogate pair is rejected.
#[derive(Clone, Debug)]
pub struct Utf16OffsetMap {
    boundaries: Vec<(usize, usize)>,
}

impl Utf16OffsetMap {
    /// Builds an offset map for `text`.
    #[must_use]
    pub fn new(text: &str) -> Self {
        let mut boundaries = Vec::with_capacity(text.chars().count().saturating_add(1));
        let (mut utf16, mut utf8) = (0, 0);
        for character in text.chars() {
            boundaries.push((utf16, utf8));
            utf16 += character.len_utf16();
            utf8 += character.len_utf8();
        }
        boundaries.push((utf16, utf8));
        Self { boundaries }
    }

    /// Converts a UTF-16 offset to a UTF-8 byte offset when it is a valid
    /// character boundary within the mapped text.
    #[must_use]
    pub fn byte_offset(&self, utf16: usize) -> Option<usize> {
        self.boundaries
            .binary_search_by_key(&utf16, |&(unit, _)| unit)
            .ok()
            .map(|index| self.boundaries[index].1)
    }

    /// Converts a non-empty UTF-16 range to a UTF-8 byte range. Returns
    /// `None` for overflow, out-of-bounds offsets, zero-length ranges, or
    /// offsets inside a surrogate pair.
    #[must_use]
    pub fn range(&self, offset: usize, length: usize) -> Option<Range<usize>> {
        if length == 0 {
            return None;
        }
        let end = offset.checked_add(length)?;
        Some(self.byte_offset(offset)?..self.byte_offset(end)?)
    }
}

/// A validation failure in a Telegram entity's UTF-16 range.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EntityRangeError {
    /// Entity ranges must contain at least one UTF-16 code unit.
    Empty,
    /// Adding the entity offset and length overflowed `usize`.
    Overflow,
    /// The range is outside the text or points inside a surrogate pair.
    InvalidBoundary,
}

/// Error returned by strict entity parsing.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct EntityParseError {
    /// Index of the invalid entity in the supplied slice.
    pub entity_index: usize,
    /// Reason its range could not be mapped.
    pub reason: EntityRangeError,
}

// There is no Cashtag or Hashtag builder because we can't influence them in any
// way by MessageEntity, they are autogenerated by the TBA.
impl MessageEntity {
    #[must_use]
    pub const fn new(kind: MessageEntityKind, offset: usize, length: usize) -> Self {
        Self { kind, offset, length }
    }

    /// Create a message entity representing a bold text.
    #[must_use]
    pub const fn bold(offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Bold, offset, length }
    }

    /// Create a message entity representing an italic text.
    #[must_use]
    pub const fn italic(offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Italic, offset, length }
    }

    /// Create a message entity representing an underline text.
    #[must_use]
    pub const fn underline(offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Underline, offset, length }
    }

    /// Create a message entity representing a strikethrough text.
    #[must_use]
    pub const fn strikethrough(offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Strikethrough, offset, length }
    }

    /// Create a message entity representing a spoiler text.
    #[must_use]
    pub const fn spoiler(offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Spoiler, offset, length }
    }

    /// Create a message entity representing a monowidth text.
    #[must_use]
    pub const fn code(offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Code, offset, length }
    }

    /// Create a message entity representing a monowidth block.
    #[must_use]
    pub const fn pre(language: Option<String>, offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::Pre { language }, offset, length }
    }

    /// Create a message entity representing a clickable text URL.
    #[must_use]
    pub const fn text_link(url: reqwest::Url, offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::TextLink { url }, offset, length }
    }

    /// Create a message entity representing a text mention.
    ///
    /// # Note
    ///
    /// If you don't have a complete [`User`] value, please use
    /// [`MessageEntity::text_mention_id`] instead.
    #[must_use]
    pub const fn text_mention(user: User, offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::TextMention { user }, offset, length }
    }

    /// Create a message entity representing a text link in the form of
    /// `tg://user/?id=...` that mentions user with `user_id`.
    #[must_use]
    pub fn text_mention_id(user_id: UserId, offset: usize, length: usize) -> Self {
        Self { kind: MessageEntityKind::TextLink { url: user_id.url() }, offset, length }
    }

    /// Create a message entity representing a custom emoji.
    #[must_use]
    pub const fn custom_emoji(
        custom_emoji_id: CustomEmojiId,
        offset: usize,
        length: usize,
    ) -> Self {
        Self { kind: MessageEntityKind::CustomEmoji { custom_emoji_id }, offset, length }
    }

    #[must_use]
    pub fn kind(mut self, val: MessageEntityKind) -> Self {
        self.kind = val;
        self
    }

    #[must_use]
    pub const fn offset(mut self, val: usize) -> Self {
        self.offset = val;
        self
    }

    #[must_use]
    pub const fn length(mut self, val: usize) -> Self {
        self.length = val;
        self
    }
}

impl<'a> MessageEntityRef<'a> {
    /// Returns kind of this entity.
    #[must_use]
    pub fn kind(&self) -> &'a MessageEntityKind {
        self.kind
    }

    /// Returns the text that this entity is related to.
    #[must_use]
    pub fn text(&self) -> &'a str {
        &self.message[self.range.clone()]
    }

    /// Returns range that this entity is related to.
    ///
    /// The range is in bytes for UTF-8 encoding i.e. you can use it with common
    /// Rust strings.
    #[must_use]
    pub fn range(&self) -> Range<usize> {
        self.range.clone()
    }

    /// Returns the offset (in bytes, for UTF-8) to the start of this entity in
    /// the original message.
    #[must_use]
    pub fn start(&self) -> usize {
        self.range.start
    }

    /// Returns the offset (in bytes, for UTF-8) to the end of this entity in
    /// the original message.
    #[must_use]
    pub fn end(&self) -> usize {
        self.range.end
    }

    /// Returns the length of this entity in bytes for UTF-8 encoding.
    #[allow(clippy::len_without_is_empty)]
    #[must_use]
    pub fn len(&self) -> usize {
        self.range.len()
    }

    /// Returns the full text of the original message.
    #[must_use]
    pub fn message_text(&self) -> &'a str {
        self.message
    }

    /// Parses telegram [`MessageEntity`]s converting offsets to UTF-8.
    ///
    /// Entities that cannot be mapped exactly are dropped: an offset that
    /// overflows, points past the end of the text, or lands inside a
    /// character (for example between the surrogates of a non-BMP character)
    /// would otherwise produce a range that panics on slicing. Callers can
    /// therefore use [`MessageEntityRef::text`] without additional checks.
    #[must_use]
    pub fn parse(text: &'a str, entities: &'a [MessageEntity]) -> Vec<Self> {
        Self::parse_lossy(text, entities)
    }

    /// Parses entities and returns the first malformed range instead of
    /// silently dropping it.
    pub fn parse_checked(
        text: &'a str,
        entities: &'a [MessageEntity],
    ) -> Result<Vec<Self>, EntityParseError> {
        if entities.is_empty() {
            return Ok(Vec::new());
        }
        let map = Utf16OffsetMap::new(text);
        entities
            .iter()
            .enumerate()
            .map(|(entity_index, entity)| {
                let range = map.range(entity.offset, entity.length).ok_or_else(|| {
                    let reason = if entity.length == 0 {
                        EntityRangeError::Empty
                    } else if entity.offset.checked_add(entity.length).is_none() {
                        EntityRangeError::Overflow
                    } else {
                        EntityRangeError::InvalidBoundary
                    };
                    EntityParseError { entity_index, reason }
                })?;
                Ok(Self { message: text, range, kind: &entity.kind })
            })
            .collect()
    }

    /// Parses all entities whose ranges can be mapped exactly. Malformed
    /// entities are skipped, preserving the historical best-effort behavior.
    #[must_use]
    pub fn parse_lossy(text: &'a str, entities: &'a [MessageEntity]) -> Vec<Self> {
        if entities.is_empty() {
            return Vec::new();
        }
        let map = Utf16OffsetMap::new(text);
        entities
            .iter()
            .filter_map(|entity| {
                let range = if entity.length == 0 {
                    // Keep the legacy parser's behavior for empty entities;
                    // strict callers can reject them with `parse_checked`.
                    let byte = map.byte_offset(entity.offset)?;
                    byte..byte
                } else {
                    map.range(entity.offset, entity.length)?
                };
                Some(Self { message: text, range, kind: &entity.kind })
            })
            .collect()
    }
}

#[serde_with::skip_serializing_none]
#[derive(Clone, Debug, Eq, Hash, PartialEq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
#[serde(rename_all = "snake_case")]
#[serde(tag = "type")]
pub enum MessageEntityKind {
    Mention,
    Hashtag,
    Cashtag,
    BotCommand,
    Url,
    Email,
    PhoneNumber,
    /// An address in the TON blockchain.
    TonAddress,
    /// A bank card number.
    BankCardNumber,
    Bold,
    Blockquote,
    ExpandableBlockquote,
    Italic,
    Underline,
    Strikethrough,
    Spoiler,
    Code,
    Pre {
        language: Option<String>,
    },
    TextLink {
        url: reqwest::Url,
    },
    TextMention {
        user: User,
    },
    CustomEmoji {
        custom_emoji_id: CustomEmojiId,
    },
    DateTime {
        unix_time: Option<i64>,
        date_time_format: Option<String>,
    },
    /// Unknown entity kind from a newer Telegram Bot API version.
    ///
    /// Forward-compatibility fallback: a new `type` tag no longer fails the
    /// whole message deserialization.
    #[serde(other)]
    Unknown,
}

#[cfg(test)]
mod tests {
    use super::*;
    use cool_asserts::assert_matches;
    use proptest::prelude::*;
    use MessageEntityKind::*;

    #[test]
    fn recursive_kind() {
        use serde_json::from_str;

        assert_eq!(
            MessageEntity {
                kind: MessageEntityKind::TextLink {
                    url: reqwest::Url::parse("https://example.com").unwrap(),
                },
                offset: 1,
                length: 2,
            },
            from_str::<MessageEntity>(
                r#"{"type":"text_link","url":"https://example.com","offset":1,"length":2}"#
            )
            .unwrap()
        );
    }

    // https://github.com/teloxide/teloxide/issues/1062
    #[test]
    fn blockquote() {
        use serde_json::from_str;

        assert_eq!(
            MessageEntity { kind: MessageEntityKind::Blockquote, offset: 32, length: 92 },
            from_str::<MessageEntity>(r#"{"type": "blockquote", "offset": 32, "length": 92}"#)
                .unwrap()
        );
    }

    #[test]
    fn expandable_blockquote() {
        use serde_json::from_str;

        assert_eq!(
            MessageEntity {
                kind: MessageEntityKind::ExpandableBlockquote,
                offset: 69,
                length: 420
            },
            from_str::<MessageEntity>(
                r#"{"type": "expandable_blockquote", "offset": 69, "length": 420}"#
            )
            .unwrap()
        );
    }

    #[test]
    fn pre() {
        use serde_json::from_str;

        assert_eq!(
            MessageEntity {
                kind: MessageEntityKind::Pre { language: Some("rust".to_string()) },
                offset: 1,
                length: 2,
            },
            from_str::<MessageEntity>(r#"{"type":"pre","offset":1,"length":2,"language":"rust"}"#)
                .unwrap()
        );
    }

    // https://github.com/teloxide/teloxide-core/pull/145
    #[test]
    fn pre_with_none_language() {
        use serde_json::to_string;

        assert_eq!(
            to_string(&MessageEntity {
                kind: MessageEntityKind::Pre { language: None },
                offset: 1,
                length: 2,
            })
            .unwrap()
            .find("language"),
            None
        );
    }

    #[test]
    fn parse_быба() {
        let parsed = MessageEntityRef::parse(
            "быба",
            &[
                MessageEntity { kind: Strikethrough, offset: 0, length: 1 },
                MessageEntity { kind: Bold, offset: 1, length: 1 },
                MessageEntity { kind: Italic, offset: 2, length: 1 },
                MessageEntity { kind: Code, offset: 3, length: 1 },
            ],
        );

        assert_matches!(
            parsed,
            [entity if entity.text() == "б" && entity.kind() == &Strikethrough, entity if entity.text() == "ы" && entity.kind() == &Bold, entity if entity.text() == "б" && entity.kind() == &Italic, entity if entity.text() == "а" && entity.kind() == &Code]
        );
    }

    #[test]
    fn parse_symbol_24bit() {
        let parsed = MessageEntityRef::parse(
            "xx আ #tt",
            &[MessageEntity { kind: Hashtag, offset: 5, length: 3 }],
        );

        assert_matches!(parsed, [entity if entity.text() == "#tt" && entity.kind() == &Hashtag]);
    }

    #[test]
    fn parse_enclosed() {
        let parsed = MessageEntityRef::parse(
            "b i b",
            // For some reason this is how telegram encodes <b>b <i>i<i/> b<b/>
            &[
                MessageEntity { kind: Bold, offset: 0, length: 2 },
                MessageEntity { kind: Bold, offset: 2, length: 3 },
                MessageEntity { kind: Italic, offset: 2, length: 1 },
            ],
        );

        assert_matches!(
            parsed,
            [entity if entity.text() == "b " && entity.kind() == &Bold, entity if entity.text() == "i b" && entity.kind() == &Bold, entity if entity.text() == "i" && entity.kind() == &Italic]
        );
    }

    #[test]
    fn parse_nothing() {
        let parsed = MessageEntityRef::parse("a", &[]);
        assert_eq!(parsed, []);
    }

    #[test]
    fn unknown_entity_kind_falls_back_instead_of_failing() {
        use serde_json::from_str;

        assert_eq!(
            MessageEntity { kind: MessageEntityKind::Unknown, offset: 0, length: 1 },
            from_str::<MessageEntity>(r#"{"type": "some_future_kind", "offset": 0, "length": 1}"#)
                .unwrap()
        );
    }

    #[test]
    fn parse_misaligned_offsets_does_not_panic() {
        // Offsets pointing past the end of the text are dropped instead of
        // panicking.
        let parsed = MessageEntityRef::parse(
            "быба",
            &[MessageEntity { kind: Bold, offset: 0, length: 100 }],
        );

        assert_eq!(parsed, []);
    }

    #[test]
    fn parse_offset_inside_emoji_is_dropped() {
        // Offset 1 lands between the surrogates of 😀 (UTF-16 units 0..2);
        // keeping it would panic on slicing, so the entity is dropped.
        let parsed =
            MessageEntityRef::parse("😀a", &[MessageEntity { kind: Bold, offset: 1, length: 1 }]);

        assert_eq!(parsed, []);
    }

    #[test]
    fn parse_overflowing_offsets_are_dropped() {
        let parsed = MessageEntityRef::parse(
            "text",
            &[MessageEntity { kind: Bold, offset: usize::MAX, length: 1 }],
        );

        assert_eq!(parsed, []);
    }

    #[test]
    fn parse_surviving_entities_slice_safely() {
        let parsed =
            MessageEntityRef::parse("😀a", &[MessageEntity { kind: Bold, offset: 0, length: 2 }]);

        assert_eq!(parsed.len(), 1);
        assert_eq!(parsed[0].text(), "😀");
    }

    #[test]
    fn checked_parse_reports_utf16_surrogate_split() {
        let err = MessageEntityRef::parse_checked(
            "😀a",
            &[MessageEntity { kind: Bold, offset: 1, length: 1 }],
        )
        .unwrap_err();
        assert_eq!(
            err,
            EntityParseError { entity_index: 0, reason: EntityRangeError::InvalidBoundary }
        );
    }

    #[test]
    fn checked_parse_distinguishes_empty_and_overflow() {
        let empty = MessageEntityRef::parse_checked(
            "text",
            &[MessageEntity { kind: Bold, offset: 0, length: 0 }],
        )
        .unwrap_err();
        assert_eq!(empty.reason, EntityRangeError::Empty);

        let overflow = MessageEntityRef::parse_checked(
            "text",
            &[MessageEntity { kind: Bold, offset: usize::MAX, length: 2 }],
        )
        .unwrap_err();
        assert_eq!(overflow.reason, EntityRangeError::Overflow);
    }

    #[test]
    fn checked_parse_keeps_valid_ranges_and_reports_original_index() {
        let entities = [
            MessageEntity { kind: Bold, offset: 99, length: 1 },
            MessageEntity { kind: Italic, offset: 2, length: 1 },
        ];
        let err = MessageEntityRef::parse_checked("😀a", &entities).unwrap_err();
        assert_eq!(err.entity_index, 0);

        let parsed = MessageEntityRef::parse_checked("😀a", &entities[1..]).unwrap();
        assert_eq!(parsed[0].text(), "a");
    }

    #[test]
    fn offset_map_checks_ranges_and_allows_end_boundary() {
        let map = Utf16OffsetMap::new("😀a");
        assert_eq!(map.byte_offset(0), Some(0));
        assert_eq!(map.byte_offset(2), Some(4));
        assert_eq!(map.byte_offset(3), Some(5));
        assert_eq!(map.byte_offset(1), None);
        assert_eq!(map.range(0, 2), Some(0..4));
        assert_eq!(map.range(usize::MAX, 1), None);
        assert_eq!(map.range(0, 0), None);
    }

    proptest::proptest! {
        #![proptest_config(proptest::test_runner::Config::with_cases(2048))]
        #[test]
        fn offset_map_matches_rust_char_boundaries(text in ".*") {
            let map = Utf16OffsetMap::new(&text);
            let mut utf16 = 0usize;
            for (byte, character) in text.char_indices() {
                prop_assert_eq!(map.byte_offset(utf16), Some(byte));
                utf16 += character.len_utf16();
                prop_assert_eq!(map.byte_offset(utf16), Some(byte + character.len_utf8()));
            }
            prop_assert_eq!(map.byte_offset(usize::MAX), None);
            prop_assert!(MessageEntityRef::parse_checked(&text, &[]).unwrap().is_empty());
        }
    }

    #[test]
    fn parse_empty() {
        // It should be impossible for this to be returned from telegram, but just to be
        // sure
        let parsed = MessageEntityRef::parse(
            "",
            &[
                MessageEntity { kind: Bold, offset: 0, length: 0 },
                MessageEntity { kind: Italic, offset: 0, length: 0 },
            ],
        );

        assert_matches!(
            parsed,
            [entity if entity.text() == "" && entity.kind() == &Bold, entity if entity.text() == "" && entity.kind() == &Italic]
        );
    }
}
